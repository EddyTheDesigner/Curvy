import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('./',import.meta.url);
const source='// Curvy 1.1.0 — EffectCraft ScriptUI panel\n// Generated by node build.mjs. Edit src/.\n'+(await Promise.all(['core.js','host.js','panel.js'].map(f=>readFile(new URL('src/'+f,root),'utf8')))).join('\n').replace(/\r\n?/g,'\n');
await mkdir(new URL('dist/',root),{recursive:true});
await writeFile(new URL('dist/Curvy.jsx',root),source);
await writeFile(new URL('dist/Curvy.jsx.sha256',root),createHash('sha256').update(source).digest('hex')+'\n');
console.log('Built dist/Curvy.jsx');
